import os
import sys
import cv2
from pathlib import Path
from tqdm import tqdm

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from tools import Stringparsing, parse_coord_str

CCPD_ROOT = Path(__file__).resolve().parents[1] / "CCPD2019"
DATASET_DIR = Path(__file__).resolve().parents[1] / "dataset"
SPLITS_DIR = CCPD_ROOT / "splits"

SPLITS = {
    "train": "train.txt",
    "val": "val.txt",
    "test": "test.txt",
}


def process_split(split_name, split_file):
    with open(split_file, "r") as f:
        lines = [line.strip() for line in f if line.strip()]

    count = 0
    pbar = tqdm(lines, desc=f"[{split_name}] 处理中", unit="img")
    for rel_path in pbar:
        img_path = CCPD_ROOT / rel_path
        if not img_path.exists():
            pbar.set_postfix_str(f"skip: missing {img_path.name}")
            continue

        filename = img_path.name
        try:
            data = Stringparsing(filename)
        except ValueError as e:
            pbar.set_postfix_str(f"skip: parse fail {filename}")
            continue

        bbox_str = data["bbox"]
        parts = bbox_str.split("_")
        x1, y1 = parse_coord_str(parts[0])
        x2, y2 = parse_coord_str(parts[1])

        img = cv2.imread(str(img_path))
        if img is None:
            pbar.set_postfix_str(f"skip: unreadable {img_path.name}")
            continue
        H, W = img.shape[:2]

        xc = (x1 + x2) / 2.0 / W
        yc = (y1 + y2) / 2.0 / H
        w = (x2 - x1) / W
        h = (y2 - y1) / H

        xc = max(0.0, min(1.0, xc))
        yc = max(0.0, min(1.0, yc))
        w = max(0.0, min(1.0, w))
        h = max(0.0, min(1.0, h))

        stem = os.path.splitext(filename)[0]
        label_path = img_path.with_suffix(".txt")

        with open(label_path, "w") as f:
            f.write(f"0 {xc:.6f} {yc:.6f} {w:.6f} {h:.6f}\n")

        count += 1

    pbar.close()
    print(f"  [{split_name}] 完成: {count} 个标签已生成")
    return count


def generate_image_lists():
    """为每个 split 生成包含绝对路径的图片列表文件到 dataset/"""
    DATASET_DIR.mkdir(parents=True, exist_ok=True)

    for split_name, filename in SPLITS.items():
        split_file = SPLITS_DIR / filename
        if not split_file.exists():
            continue

        out_path = DATASET_DIR / f"{split_name}.txt"
        with open(split_file, "r") as fin, open(out_path, "w") as fout:
            for line in fin:
                rel = line.strip()
                if rel:
                    fout.write(f"{(CCPD_ROOT / rel).as_posix()}\n")
        print(f"  [{split_name}] 图片列表已生成: {out_path}")


def generate_data_yaml():
    DATASET_DIR.mkdir(parents=True, exist_ok=True)

    yaml_path = DATASET_DIR / "data.yaml"
    content = f"""# CCPD2019 YOLO dataset
# Generated by process_dataset.py

train: {DATASET_DIR.as_posix()}/train.txt
val: {DATASET_DIR.as_posix()}/val.txt
test: {DATASET_DIR.as_posix()}/test.txt

nc: 1
names: ['license_plate']
"""
    with open(yaml_path, "w") as f:
        f.write(content)
    print(f"data.yaml 已生成: {yaml_path}")


if __name__ == "__main__":
    print("=" * 50)
    print("CCPD2019 → YOLO 格式转换")
    print(f"CCPD2019 根目录: {CCPD_ROOT}")
    print("=" * 50)

    total = 0
    for split_name, filename in SPLITS.items():
        split_file = SPLITS_DIR / filename
        if not split_file.exists():
            print(f"  [SKIP] 找不到 split 文件: {split_file}")
            continue
        print(f"\n正在处理 {split_name}...")
        cnt = process_split(split_name, split_file)
        total += cnt

    print(f"\n总计生成 {total} 个标签文件")
    generate_image_lists()
    generate_data_yaml()
    print("\n完成!")
